// Embeds dist/ into worker/assets.gen.ts so the Worker serves the PWA without a separate asset upload.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, extname } from 'node:path'

const DIST = 'dist'
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8', '.woff2': 'font/woff2' }
const TEXT = new Set(['.html', '.js', '.css', '.json', '.webmanifest', '.svg', '.txt'])
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]))
const out = {}
let total = 0
for (const file of walk(DIST)) {
  const ext = extname(file)
  const buf = readFileSync(file)
  total += buf.length
  out['/' + relative(DIST, file).split('\\').join('/')] = TEXT.has(ext)
    ? { type: TYPES[ext] ?? 'text/plain', b64: false, body: buf.toString('utf8') }
    : { type: TYPES[ext] ?? 'application/octet-stream', b64: true, body: buf.toString('base64') }
}
writeFileSync('worker/assets.gen.ts', `// Generated by scripts/embed-assets.mjs — do not edit.\nexport const ASSETS: Record<string, { type: string; b64: boolean; body: string }> = ${JSON.stringify(out)}\n`)
console.log(`embedded ${Object.keys(out).length} files, ${(total / 1024).toFixed(0)} KiB`)
